const SERVER_ERROR_PATTERNS: Partial<Record<Lang, Array<[RegExp, string]>>> = {
	ru: [[/^too many attempts, retry in (\d+) seconds$/, "Слишком много попыток, повторите через $1 с"]],
}

export function translateServerError(lang: Lang, message: string): string {
	const exact = SERVER_ERRORS[lang]?.[message]
	if (exact) return exact
	for (const [pattern, replacement] of SERVER_ERROR_PATTERNS[lang] ?? []) {
		if (pattern.test(message)) return message.replace(pattern, replacement)
	}
	return message
}

// Code outside React (the API client, error helpers) needs the language the
// user picked; the settings provider keeps this in sync.
let activeLang: Lang = "en"

export function setActiveLang(lang: Lang): void {
	activeLang = lang
}

export function getActiveLang(): Lang {
	return activeLang
}

// Hour and minute fields for the language's clock: "2:05 PM" (no leading
// zero, as English writes it) or "09:05".
export function timeFields(lang: Lang): Intl.DateTimeFormatOptions {
	return LANG_INFO[lang].hour12
		? { hour: "numeric", minute: "2-digit", hour12: true }
		: { hour: "2-digit", minute: "2-digit", hour12: false }
}

export function formatTimeOfDay(lang: Lang, iso: string): string {
	const date = new Date(iso)
	if (Number.isNaN(date.getTime())) return ""
	return date.toLocaleTimeString(localeOf(lang), timeFields(lang))
}

export function formatDateTime(lang: Lang, iso: string, options?: Intl.DateTimeFormatOptions): string {
	const date = new Date(iso)
	if (Number.isNaN(date.getTime())) return ""
	return date.toLocaleString(localeOf(lang), options ?? { year: "numeric", month: "short", day: "numeric", ...timeFields(lang) })
}

// "Last seen" wording: relative within the last hour, then by calendar day —
// today, yesterday, a date this year, or just the date for older visits.
export function formatLastSeen(lang: Lang, iso: string, now: number = Date.now()): string {
	const date = new Date(iso)
	const time = date.getTime()
	if (Number.isNaN(time)) return ""
	const minutes = Math.floor(Math.max(0, now - time) / 60000)
	if (minutes < 1) return translate(lang, "lastSeenJustNow")
	if (minutes < 60) return plural(lang, "lastSeenMinutes", minutes)
	const clock = formatTimeOfDay(lang, iso)
	const today = new Date(now)
	today.setHours(0, 0, 0, 0)
	const day = new Date(time)
	day.setHours(0, 0, 0, 0)
	const days = Math.round((today.getTime() - day.getTime()) / 86400000)
	if (days <= 0) return format(translate(lang, "lastSeenToday"), { time: clock })
	if (days === 1) return format(translate(lang, "lastSeenYesterday"), { time: clock })
	const month = LANG_INFO[lang].dayMonth
	if (date.getFullYear() === today.getFullYear()) {
		return format(translate(lang, "lastSeenOnDay"), { date: formatDate(lang, date, { day: "numeric", month }), time: clock })
	}
	return format(translate(lang, "lastSeenOnDate"), { date: formatDate(lang, date, { day: "numeric", month, year: "numeric" }) })
}

// Sizes in the units of the language ("2 MB", "2 МБ"), in steps of 1024.
const BYTE_UNITS = ["byte", "kilobyte", "megabyte", "gigabyte", "terabyte"] as const
export function formatBytes(lang: Lang, size: number): string {
	if (!Number.isFinite(size) || size < 0) return ""
	let value = size
	let unit = 0
	while (value >= 1024 && unit < BYTE_UNITS.length - 1) {
		value /= 1024
		unit += 1
	}
	return new Intl.NumberFormat(localeOf(lang), {
		style: "unit",
		unit: BYTE_UNITS[unit],
		unitDisplay: unit === 0 ? "narrow" : "short",
		maximumFractionDigits: unit === 0 || value >= 100 ? 0 : 1,
	}).format(value)
}

export function formatDate(lang: Lang, date: Date, options: Intl.DateTimeFormatOptions): string {
	return date.toLocaleDateString(localeOf(lang), options)
}

