// Every language-specific detail lives in this file. Adding a language means:
// 1) add its code to Lang, 2) describe it in LANG_INFO, 3) add a dictionary
// (missing keys fall back to English), 4) add its plural forms and, if wanted,
// its server error translations. Components never compare against a language
// code themselves; they call translate(), plural(), formatTime() and friends.
export type Lang = "en" | "ru"

type LangInfo = {
	label: string
	// BCP 47 tag used for dates, numbers and plural rules.
	locale: string
	// 12-hour clock with AM/PM (English) or 24-hour (Russian).
	hour12: boolean
	// Month in "day month" dates: "26 сентября" or "Sep 26".
	dayMonth: "long" | "short"
}

// Order here is the order of the language switcher.
const LANG_INFO: Record<Lang, LangInfo> = {
	ru: { label: "Русский", locale: "ru-RU", hour12: false, dayMonth: "long" },
	en: { label: "English", locale: "en-US", hour12: true, dayMonth: "short" },
}

export const LANGS: ReadonlyArray<{ code: Lang; label: string }> = (Object.keys(LANG_INFO) as Lang[]).map((code) => ({
	code,
	label: LANG_INFO[code].label,
}))

export function isLang(value: unknown): value is Lang {
	return typeof value === "string" && Object.prototype.hasOwnProperty.call(LANG_INFO, value)
}

// Picks the best supported language for a browser tag such as "ru-RU".
export function langFromTag(tag: string | null | undefined): Lang {
	const base = String(tag ?? "").toLowerCase().split(/[-_]/)[0]
	return isLang(base) ? base : "en"
}

export function localeOf(lang: Lang): string {
	return LANG_INFO[lang].locale
}

