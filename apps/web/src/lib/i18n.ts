const DICTIONARIES: Record<Lang, Partial<Record<StringKey, string>>> = { en, ru }

export function translate(lang: Lang, key: StringKey): string {
	return DICTIONARIES[lang][key] || en[key]
}

// Fills {name} placeholders: format("{n} of {total}", { n: 1, total: 3 }).
export function format(template: string, values: Record<string, string | number>): string {
	return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in values ? String(values[name]) : whole))
}

// Plural forms follow Intl.PluralRules categories. "other" is required, the
// rest only where the language distinguishes them ({n} is the count).
type PluralForms = Partial<Record<Intl.LDMLPluralRule, string>> & { other: string }
type PluralKey = "votes" | "comments" | "messages" | "otherDevicesSignedOut" | "lastSeenMinutes" | "membersCount" | "subscribersCount"

const PLURALS: Record<Lang, Record<PluralKey, PluralForms>> = {
	en: {
		votes: { one: "{n} vote", other: "{n} votes" },
		comments: { one: "{n} comment", other: "{n} comments" },
		messages: { one: "{n} message", other: "{n} messages" },
		otherDevicesSignedOut: { one: "Signed out {n} other device", other: "Signed out {n} other devices" },
		lastSeenMinutes: { one: "last seen {n} minute ago", other: "last seen {n} minutes ago" },
		membersCount: { one: "{n} member", other: "{n} members" },
		subscribersCount: { one: "{n} subscriber", other: "{n} subscribers" },
	},
	ru: {
		votes: { one: "{n} голос", few: "{n} голоса", many: "{n} голосов", other: "{n} голоса" },
		comments: { one: "{n} комментарий", few: "{n} комментария", many: "{n} комментариев", other: "{n} комментария" },
		messages: { one: "{n} сообщение", few: "{n} сообщения", many: "{n} сообщений", other: "{n} сообщения" },
		otherDevicesSignedOut: { one: "Завершён {n} другой сеанс", few: "Завершено {n} других сеанса", many: "Завершено {n} других сеансов", other: "Завершено {n} других сеанса" },
		lastSeenMinutes: { one: "был(а) в сети {n} минуту назад", few: "был(а) в сети {n} минуты назад", many: "был(а) в сети {n} минут назад", other: "был(а) в сети {n} минуты назад" },
		membersCount: { one: "{n} участник", few: "{n} участника", many: "{n} участников", other: "{n} участника" },
		subscribersCount: { one: "{n} подписчик", few: "{n} подписчика", many: "{n} подписчиков", other: "{n} подписчика" },
	},
}

const pluralRules = new Map<Lang, Intl.PluralRules>()

export function plural(lang: Lang, key: PluralKey, count: number): string {
	let rules = pluralRules.get(lang)
	if (!rules) {
		rules = new Intl.PluralRules(localeOf(lang))
		pluralRules.set(lang, rules)
	}
	const forms = PLURALS[lang][key] ?? PLURALS.en[key]
	return format(forms[rules.select(count)] ?? forms.other, { n: count })
}

