// Builds src/lib/emojiData.ts from Unicode's emoji-test.txt: every fully
// qualified emoji in the standard order, grouped the way phones group them.
// Skin-tone and hair variants are left out (the base emoji covers them).
//
// With --cldr it also builds src/lib/emojiNames.ts, the search index of the
// emoji panel: the English name from emoji-test.txt plus the CLDR names and
// keywords of every listed language (annotations/<lang>/annotations.json and
// annotationsDerived/<lang>/annotations.json from the cldr-json packages,
// saved as <lang>.json and <lang>-derived.json in that directory).
//
//   node scripts/gen-emoji.mjs [path-or-url-to-emoji-test.txt] [--cldr dir] [--langs en,ru]

import { readFile, writeFile } from "node:fs/promises"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const args = process.argv.slice(2)
const option = (name) => {
	const at = args.indexOf(name)
	if (at < 0) return null
	const value = args[at + 1]
	args.splice(at, 2)
	return value
}
const cldrDir = option("--cldr")
const langs = (option("--langs") ?? "en,ru").split(",").map((lang) => lang.trim()).filter(Boolean)
const source = args[0] ?? "https://unicode.org/Public/emoji/latest/emoji-test.txt"
const text = source.startsWith("http") ? await (await fetch(source)).text() : await readFile(source, "utf8")

const GROUPS = {
	"Smileys & Emotion": { key: "smileys", icon: "😀" },
	"People & Body": { key: "people", icon: "👋" },
	"Animals & Nature": { key: "nature", icon: "🐶" },
	"Food & Drink": { key: "food", icon: "🍔" },
	"Activities": { key: "activity", icon: "⚽" },
	"Travel & Places": { key: "travel", icon: "🚗" },
	"Objects": { key: "objects", icon: "💡" },
	"Symbols": { key: "symbols", icon: "❤️" },
	"Flags": { key: "flags", icon: "🏳️" },
}

const MAX_VERSION = Number(process.env.EMOJI_MAX_VERSION ?? 15.0)
const out = []
const englishName = new Map()
let current = null
let version = ""
for (const line of text.split("\n")) {
	const v = /^# Version: ([\d.]+)/.exec(line)
	if (v) version = v[1]
	const g = /^# group: (.+)$/.exec(line)
	if (g) {
		const meta = GROUPS[g[1].trim()]
		current = meta ? { key: meta.key, icon: meta.icon, emoji: [] } : null
		if (current) out.push(current)
		continue
	}
	if (!current || line.startsWith("#") || !line.trim()) continue
	const m = /^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*(\S+)\s+E([\d.]+)\s+(.*)$/.exec(line)
	if (!m) continue
	// The newest emoji are missing from the fonts of most phones and
	// computers and would show as empty boxes.
	if (Number(m[3]) > MAX_VERSION) continue
	const codes = m[1].trim().split(/\s+/).map((c) => parseInt(c, 16))
	// Skin tones (1F3FB-1F3FF) and hair styles (1F9B0-1F9B3) are variants.
	if (codes.some((c) => (c >= 0x1f3fb && c <= 0x1f3ff) || (c >= 0x1f9b0 && c <= 0x1f9b3))) continue
	const emoji = String.fromCodePoint(...codes)
	current.emoji.push(emoji)
	englishName.set(emoji, m[4].trim())
}

const total = out.reduce((n, group) => n + group.emoji.length, 0)
if (total < 1000) throw new Error("emoji list looks wrong: " + total)
const body =
	"// Generated by scripts/gen-emoji.mjs from Unicode emoji-test.txt" + (version ? " (Emoji " + version + ")" : "") + ". Do not edit.\n\n" +
	"export type EmojiGroupKey = " + out.map((group) => JSON.stringify(group.key)).join(" | ") + "\n\n" +
	"export const EMOJI_DATA: Array<{ key: EmojiGroupKey; icon: string; emoji: string[] }> = " + JSON.stringify(out, null, "\t") + "\n"
const libDir = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "lib")
await writeFile(join(libDir, "emojiData.ts"), body)
console.log("wrote", total, "emoji in", out.length, "groups")

if (cldrDir) {
	// CLDR keys leave out the emoji variation selector (U+FE0F).
	const bare = (emoji) => emoji.replace(/️/g, "")
	const tables = []
	for (const lang of langs) {
		for (const file of [lang + ".json", lang + "-derived.json"]) {
			const json = JSON.parse(await readFile(join(cldrDir, file), "utf8"))
			const table = json.annotations?.annotations ?? json.annotationsDerived?.annotations
			if (!table || typeof table !== "object") throw new Error("no annotations in " + file)
			tables.push(table)
		}
	}
	const index = {}
	let named = 0
	for (const group of out) {
		for (const emoji of group.emoji) {
			const words = new Set()
			const english = englishName.get(emoji)
			if (english) words.add(english.toLowerCase())
			for (const table of tables) {
				const entry = table[bare(emoji)] ?? table[emoji]
				if (!entry) continue
				for (const word of [...(entry.tts ?? []), ...(entry.default ?? [])]) {
					if (typeof word === "string" && word.trim()) words.add(word.trim().toLowerCase())
				}
			}
			if (words.size > 0) named += 1
			index[emoji] = [...words].join("|")
		}
	}
	const names =
		"// Generated by scripts/gen-emoji.mjs from Unicode emoji-test.txt and the CLDR\n" +
		"// annotations (" + langs.join(", ") + "). Do not edit. Loaded only when someone searches.\n\n" +
		"// Emoji -> its names and keywords, lower case, separated by \"|\".\n" +
		"export const EMOJI_NAMES: Record<string, string> = " + JSON.stringify(index) + "\n"
	await writeFile(join(libDir, "emojiNames.ts"), names)
	console.log("wrote search names for", named, "of", total, "emoji in", langs.join(", "))
}
